export const VALID_ZONES = new Set(["production", "script", "test", "config", "generated", "vendor"]);
export const SCORED_ZONES = new Set(["production", "script"]);

const VENDOR_SEGMENTS = new Set([
    "node_modules", "vendor", "third_party", "third-party", "external", "submodules",
    "wallypackages", "serverpackages", "devpackages", "robloxpackages", "roblox_packages", "luau_packages", "_index",
]);

function hasRobloxManifest(rootDir) {
    if (!rootDir || typeof rootDir !== "string") return false;
    return (
        existsSync(join(rootDir, "wally.toml")) ||
        existsSync(join(rootDir, "rotriever.toml")) ||
        existsSync(join(rootDir, "aftman.toml")) ||
        existsSync(join(rootDir, "rokit.toml"))
    );
}

const GENERATED_SEGMENTS = new Set([
    "dist", "build", "out", "coverage", ".next", ".nuxt", "generated", "__generated__", "proto_gen", "__snapshots__",
]);

// Comment-only header lines like `-- @generated`, `// Code generated by X. DO NOT EDIT.`, `# auto-generated`.
const GENERATED_TAG_RE = /@generated\b|\bdo not edit\b|\bauto-?generated\b|\bcode generated by\b/i;

function readHeaderPreviewText(rootDir, relPath) {
    let fd = null;
    try {
        fd = openSync(join(rootDir, relPath), "r");
        const buf = Buffer.alloc(4096);
        return buf.toString("utf8", 0, readSync(fd, buf, 0, buf.length, 0));
    } catch {
        return null;
    } finally {
        if (fd !== null) closeSync(fd);
    }
}

function stepGeneratedHeaderCommentLine(trimmed, state) {
    if (state.luauClosePat) {
        if (GENERATED_TAG_RE.test(trimmed)) return "generated";
        if (trimmed.includes(state.luauClosePat)) state.luauClosePat = null;
        return "continue";
    }
    if (state.inCBlock) {
        if (GENERATED_TAG_RE.test(trimmed)) return "generated";
        if (trimmed.includes("*/")) state.inCBlock = false;
        return "continue";
    }
    if (trimmed.startsWith("--[")) {
        const m = /^--\[(=*)\[/.exec(trimmed);
        if (m) {
            if (GENERATED_TAG_RE.test(trimmed)) return "generated";
            const close = `]${m[1]}]`;
            if (!trimmed.slice(m[0].length).includes(close)) state.luauClosePat = close;
            return "continue";
        }
    }
    if (trimmed.startsWith("/*")) {
        if (GENERATED_TAG_RE.test(trimmed)) return "generated";
        if (!trimmed.slice(2).includes("*/")) state.inCBlock = true;
        return "continue";
    }
    if (trimmed.startsWith("//") || trimmed.startsWith("--") || trimmed.startsWith("#")) {
        return GENERATED_TAG_RE.test(trimmed) ? "generated" : "continue";
    }
    return "stop";
}

function hasGeneratedHeader(rootDir, relPath) {
    const text = readHeaderPreviewText(rootDir, relPath);
    if (!text) return false;
    const state = { inCBlock: false, luauClosePat: null };
    let nonBlank = 0;
    for (const line of text.split(/\r?\n/, 25)) {
        const trimmed = line.trim();
        if (!trimmed) continue;
        nonBlank += 1;
        if (nonBlank > 20) break;
        const step = stepGeneratedHeaderCommentLine(trimmed, state);
        if (step === "generated") return true;
        if (step === "stop") break;
    }
    return false;
}

const workflowOutputCache = new Map();

function mtimePart(absPath) {
    try {
        return String(statSync(absPath).mtimeMs);
    } catch {
        return "-";
    }
}

/**
 * Paths a CI workflow writes back to the repo, read from `file_pattern:` (git-auto-commit-action)
 * and `add:` (add-and-commit) keys in `.github/workflows/*.yml`. Hand edits to these files are
 * overwritten by the next run, so detectors must not recommend inlining or deleting them.
 */
function workflowOutputMatchers(rootDir) {
    const dir = join(rootDir, ".github", "workflows");
    let names = [];
    try {
        names = readdirSync(dir).filter((n) => /\.ya?ml$/i.test(n)).sort();
    } catch {
        // no workflows
    }
    const stamp = `${mtimePart(dir)}|${names.map((n) => `${n}:${mtimePart(join(dir, n))}`).join("|")}`;
    const cached = workflowOutputCache.get(rootDir);
    if (cached && cached.stamp === stamp) return cached.matchers;
    const matchers = [];
    for (const name of names) {
        let text = "";
        try {
            text = readFileSync(join(dir, name), "utf8");
        } catch {
            continue;
        }
        for (const m of text.matchAll(/^\s*(?:file_pattern|add)\s*:\s*["']?([^"'\n#]+)/gm)) {
            for (const pat of m[1].trim().split(/\s+/)) {
                if (/[./]/.test(pat) && pat !== "." && !pat.startsWith("-")) matchers.push(globToRegExp(pat));
            }
        }
    }
    workflowOutputCache.set(rootDir, { stamp, matchers });
    return matchers;
}

const TEST_SEGMENTS = new Set([
    "test", "tests", "__tests__", "spec", "specs", "bench", "benchmarks",
    "fixtures", "__fixtures__", "testdata", "mocks", "__mocks__",
]);

const SCRIPT_SEGMENTS = new Set(["scripts", "script", "tools", "dev", "bin", "ci"]);

const CONFIG_BASENAMES = new Set([
    "default.project.json", "sourcemap.json", "wally.toml", "wally.lock", "rokit.toml", "aftman.toml",
    "selene.toml", "stylua.toml", "package.json", "package-lock.json", "yarn.lock", "pnpm-lock.yaml",
    "bun.lock", "bun.lockb", "tsconfig.json", "jsconfig.json", "pyproject.toml", "poetry.lock",
    "cargo.lock", "gemfile.lock", "composer.lock", "setup.py", "conftest.py",
]);

const GENERATED_SUFFIX_RE =
    /\.(?:min\.js|bundle\.js|pb\.go|g\.dart|freezed\.dart|generated\.[a-z0-9]+|gen\.[a-z0-9]+|snap)$|_pb2\.py$|_gen\.go$/i;

/**
 * Classify a repo-relative path into a zone (`production`, `script`, `test`, `config`, `generated`, `vendor`).
 * User overrides in `config.zones` take highest precedence.
 */
function lookupZoneOverride(norm, zoneOverrides) {
    if (!zoneOverrides || typeof zoneOverrides !== "object") return null;
    if (zoneOverrides[norm] && VALID_ZONES.has(zoneOverrides[norm])) return zoneOverrides[norm];
    for (const [prefix, zone] of Object.entries(zoneOverrides)) {
        if (!VALID_ZONES.has(zone)) continue;
        const cleanPrefix = prefix.replace(/\\/g, "/").replace(/\/+$/, "");
        if (norm === cleanPrefix || norm.startsWith(`${cleanPrefix}/`)) return zone;
    }
    return null;
}

function classifyByDirectoryAndConfig(parts, lowerParts, base, rootDir, norm) {
    const isLuauPath = base.endsWith(".luau") || base.endsWith(".lua");
    const isRobloxRepo = hasRobloxManifest(rootDir);
    for (let i = 0; i < lowerParts.length - 1; i++) {
        const seg = lowerParts[i];
        if (VENDOR_SEGMENTS.has(seg)) return "vendor";
        if (seg === "packages" && (parts[i] === "Packages" || isLuauPath || isRobloxRepo)) return "vendor";
        if (GENERATED_SEGMENTS.has(seg)) return "generated";
    }
    if (GENERATED_SUFFIX_RE.test(base)) return "generated";
    if (rootDir && typeof rootDir === "string" && (workflowOutputMatchers(rootDir).some((rx) => rx.test(norm)) || hasGeneratedHeader(rootDir, norm))) {
        return "generated";
    }
    if (CONFIG_BASENAMES.has(base) || /\.(?:config\.(?:js|ts|mjs|cjs)|project\.json|d\.(?:ts|luau))$/.test(base)) {
        return "config";
    }
    return null;
}

export function classifyZone(relPath, zoneOverrides = {}, rootDir = null) {
    const norm = relPath.replace(/\\/g, "/").replace(/^\.\//, "");
    const override = lookupZoneOverride(norm, zoneOverrides);
    if (override) return override;
    const parts = norm.split("/");
    const lowerParts = parts.map((p) => p.toLowerCase());
    const base = lowerParts[lowerParts.length - 1] || "";
    const earlyZone = classifyByDirectoryAndConfig(parts, lowerParts, base, rootDir, norm);
    if (earlyZone) return earlyZone;
    for (const seg of lowerParts.slice(0, -1)) {
        if (TEST_SEGMENTS.has(seg)) return "test";
    }
    if (/\.(?:test|spec|story|stories|bench)\.[a-z0-9]+$/i.test(base) || /-benchmark\.[a-z0-9]+$/i.test(base) || /^test_.*\.[a-z0-9]+$/i.test(base) || /_test\.(go|py|rs|luau|lua)$/i.test(base)) {
        return "test";
    }
    if (lowerParts.length > 1 && SCRIPT_SEGMENTS.has(lowerParts[0])) return "script";
    return "production";
}

const packageEntrypointsCache = new Map();

registerGraphCacheClearer(() => {
    workflowOutputCache.clear();
    packageEntrypointsCache.clear();
});

function addPackageEntrypointCandidate(out, raw, baseSubdir = "") {
    if (!raw || typeof raw !== "string") return;
    const trimmed = raw.trim();
    if (!trimmed || /^[a-z]+:\/\//i.test(trimmed) || trimmed.includes("${")) return;
    const clean = trimmed.replace(/\\/g, "/").replace(/^\.\//, "").replace(/\/+$/, "");
    if (!clean || clean.includes("*") || clean.startsWith("..") || clean.startsWith("-")) return;
    const candidates = baseSubdir && !clean.startsWith(`${baseSubdir}/`)
        ? [clean, `${baseSubdir}/${clean}`]
        : [clean];
    for (const cand of candidates) {
        out.add(cand);
        if (!/\.[a-z0-9]+$/i.test(cand)) {
            out.add(`${cand}/init.luau`);
            out.add(`${cand}/init.lua`);
            out.add(`${cand}.luau`);
            out.add(`${cand}.lua`);
            out.add(`${cand}/index.js`);
            out.add(`${cand}/index.ts`);
            out.add(`${cand}.js`);
            out.add(`${cand}.ts`);
        }
    }
}

function collectCommandEntrypoints(rawCmd, out) {
    if (!rawCmd || typeof rawCmd !== "string") return;
    for (const tok of rawCmd.trim().split(/\s+/)) {
        const cleanTok = tok.replace(/^["']|["']$/g, "");
        if (cleanTok && !cleanTok.startsWith("-") && /[./]/.test(cleanTok)) {
            addPackageEntrypointCandidate(out, cleanTok);
        }
    }
}

function collectJsonStringsByKeys(node, targetKeys, out) {
    if (!node || typeof node !== "object") return;
    if (Array.isArray(node)) {
        for (const item of node) collectJsonStringsByKeys(item, targetKeys, out);
        return;
    }
    for (const [k, v] of Object.entries(node)) {
        if (targetKeys.has(k)) {
            if (typeof v === "string") addPackageEntrypointCandidate(out, v);
            else if (v && typeof v === "object") collectAllStringLeaves(v, out);
        } else if (v && typeof v === "object") {
            collectJsonStringsByKeys(v, targetKeys, out);
        }
    }
}

function collectAllStringLeaves(node, out) {
    if (typeof node === "string") {
        addPackageEntrypointCandidate(out, node);
        return;
    }
    if (!node || typeof node !== "object") return;
    const vals = Array.isArray(node) ? node : Object.values(node);
    for (const v of vals) collectAllStringLeaves(v, out);
}

function readJsonSafe(absPath) {
    try {
        return JSON.parse(readFileSync(absPath, "utf8"));
    } catch {
        return null;
    }
}

function collectSidecarManifestEntrypoints(rootDir, out, stampParts) {
    const sidecarsDir = join(rootDir, "sidecars");
    stampParts.push(`sidecars:${mtimePart(sidecarsDir)}`);
    let subdirs = [];
    try {
        subdirs = readdirSync(sidecarsDir, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort();
    } catch {
        return;
    }
    const keys = new Set(["main", "entry", "script", "command", "args"]);
    for (const sub of subdirs) {
        const manifestPath = join(sidecarsDir, sub, "sidecar.json");
        stampParts.push(`sidecar:${sub}:${mtimePart(manifestPath)}`);
        const parsed = readJsonSafe(manifestPath);
        if (!parsed) continue;
        const localOut = new Set();
        collectJsonStringsByKeys(parsed, keys, localOut);
        for (const cand of localOut) {
            addPackageEntrypointCandidate(out, cand, `sidecars/${sub}`);
        }
    }
}

/**
 * Load declared package/project entrypoints from `package.json`, `plugin.json`, `hooks.json`,
 * `sidecars/<dir>/sidecar.json`, `pyproject.toml`, `Cargo.toml`, and Rojo `*.project.json` under `rootDir`
 * so public entrypoints are never flagged dead.
 */
function computeEntrypointCacheStamp(rootDir, manifestRelPaths) {
    const stampParts = [
        `pkg:${mtimePart(join(rootDir, "package.json"))}`,
        `py:${mtimePart(join(rootDir, "pyproject.toml"))}`,
        `cargo:${mtimePart(join(rootDir, "Cargo.toml"))}`,
        `root:${mtimePart(rootDir)}`,
    ];
    for (const rel of manifestRelPaths) {
        stampParts.push(`${rel}:${mtimePart(join(rootDir, rel))}`);
    }
    stampParts.push(mtimePart(join(rootDir, "sidecars")));
    try {
        for (const d of readdirSync(join(rootDir, "sidecars"), { withFileTypes: true })) {
            if (d.isDirectory()) {
                stampParts.push(`${d.name}:${mtimePart(join(rootDir, "sidecars", d.name, "sidecar.json"))}`);
            }
        }
    } catch {
        // no sidecars dir
    }
    return stampParts.join("|");
}

function collectManifestEntrypoints(rootDir, relPaths, keys, out) {
    for (const rel of relPaths) {
        const manifest = readJsonSafe(join(rootDir, rel));
        if (!manifest) continue;
        collectJsonStringsByKeys(manifest, keys, out);
        const cmdOut = new Set();
        collectJsonStringsByKeys(manifest, new Set(["command"]), cmdOut);
        for (const c of cmdOut) collectCommandEntrypoints(c, out);
    }
}

function collectProjectAndRustAndPyEntrypoints(rootDir, out) {
    try {
        for (const fname of readdirSync(rootDir)) {
            if (!fname.endsWith(".project.json")) continue;
            const proj = readJsonSafe(join(rootDir, fname));
            if (proj) collectJsonStringsByKeys(proj, new Set(["$path"]), out);
        }
    } catch {
        // Ignore unreadable root
    }

    const pyPath = join(rootDir, "pyproject.toml");
    if (existsSync(pyPath)) {
        try {
            const pyText = readFileSync(pyPath, "utf8");
            const secRe = /\[(?:project\.scripts|project\.gui-scripts|tool\.poetry\.scripts)\]([\s\S]*?)(?=\n\[|$)/g;
            for (const sec of pyText.matchAll(secRe)) {
                for (const m of sec[1].matchAll(/=\s*["']([^"':]+):/g)) {
                    const modPath = m[1].trim().replace(/\./g, "/");
                    if (!modPath) continue;
                    out.add(`${modPath}.py`);
                    out.add(`src/${modPath}.py`);
                    out.add(`${modPath}/__init__.py`);
                    out.add(`src/${modPath}/__init__.py`);
                }
            }
        } catch {
            // Ignore unreadable pyproject.toml
        }
    }

    const cargoPath = join(rootDir, "Cargo.toml");
    if (existsSync(cargoPath)) {
        try {
            const cargoText = readFileSync(cargoPath, "utf8");
            out.add("src/lib.rs");
            out.add("src/main.rs");
            for (const m of cargoText.matchAll(/^\s*path\s*=\s*["']([^"']+)["']/gm)) {
                addPackageEntrypointCandidate(out, m[1]);
            }
        } catch {
            // Ignore unreadable Cargo.toml
        }
    }
}

export function loadPackageEntrypoints(rootDir) {
    const out = new Set();
    if (!rootDir || typeof rootDir !== "string") return out;

    const pluginManifestRelPaths = ["plugin.json", ".claude-plugin/plugin.json", ".gemini/plugin.json"];
    const hookManifestRelPaths = ["hooks.json", "hooks/hooks.json"];
    const previewStamp = computeEntrypointCacheStamp(rootDir, [...pluginManifestRelPaths, ...hookManifestRelPaths]);
    const cached = packageEntrypointsCache.get(rootDir);
    if (cached && cached.stamp === previewStamp) return cached.out;

    const pkg = readJsonSafe(join(rootDir, "package.json"));
    if (pkg) {
        collectJsonStringsByKeys(pkg, new Set(["main", "module", "types", "typings", "bin", "exports"]), out);
    }

    collectManifestEntrypoints(
        rootDir,
        pluginManifestRelPaths,
        new Set(["main", "entry", "script", "mcpServers", "skills", "commands", "agents", "hooks", "sidecars", "args"]),
        out,
    );
    collectManifestEntrypoints(rootDir, hookManifestRelPaths, new Set(["hooks", "script", "entry", "args"]), out);
    collectSidecarManifestEntrypoints(rootDir, out, []);
    collectProjectAndRustAndPyEntrypoints(rootDir, out);

    packageEntrypointsCache.set(rootDir, { stamp: previewStamp, out });
    return out;
}

/**
 * Distinguish non-unit-test support files inside test/bench directories (`bench/`, `fixtures/`, `mocks/`, `helpers`)
 * so hollow-test checks do not false-positive on benchmarks or test fixtures.
 */
export function isSupportOrBenchFile(relPath) {
    const norm = relPath.replace(/\\/g, "/").toLowerCase();
    const parts = norm.split("/");
    const base = basename(norm);
    for (const seg of parts.slice(0, -1)) {
        if (
            seg === "bench" ||
            seg === "benchmarks" ||
            seg === "fixtures" ||
            seg === "__fixtures__" ||
            seg === "testdata" ||
            seg === "mocks" ||
            seg === "__mocks__" ||
            seg === "helpers" ||
            seg === "test-helpers"
        ) {
            return true;
        }
    }
    return (
        base === "conftest.py" ||
        /^setup\.[a-z0-9]+$/.test(base) ||
        /^helpers?\.[a-z0-9]+$/.test(base) ||
        /\.(?:bench|story|stories)\.[a-z0-9]+$/.test(base) ||
        /-benchmark\.[a-z0-9]+$/.test(base)
    );
}

function isPathIgnoredByRules(rules, relPath, detectorOrCategory = null, ledger = null) {
    const norm = relPath.replace(/\\/g, "/").replace(/^\.\//, "");
    const cat = detectorOrCategory ? String(detectorOrCategory).toLowerCase().replace(/-/g, "_") : null;
    for (const r of rules) {
        if (r.category && cat && r.category !== cat && DETECTOR_CATEGORY[cat] !== r.category) {
            continue;
        }
        if (r.category && !cat) continue;
        if (
            norm === r.pattern ||
            norm.startsWith(`${r.pattern}/`) ||
            norm.includes(`/${r.pattern}/`) ||
            (r.regex && r.regex.test(norm))
        ) {
            if (ledger && !r.fromConfigExclude && cat) {
                ledger.record(r.category || "all", norm, null, "plexerignore");
            }
            return true;
        }
    }
    return false;
}

function normalizeLedgerFile(file) {
    return file ? String(file).replace(/\\/g, "/").replace(/^\.\//, "") : "";
}

function recordSuppressionLedgerEntry(entries, lineKeys, fileKeys, detector, file, line, kind, isFile) {
    const det = String(detector || "all").toLowerCase();
    const normFile = normalizeLedgerFile(file);
    const key = `${det}::${normFile}::${line ?? "*"}::${kind}`;
    if (!entries.has(key)) {
        entries.set(key, { detector: det, file: normFile, line, kind });
    }
    if (!normFile) return;
    if (line !== null && line !== undefined) {
        lineKeys.set(`${det}::${normFile}::${line}`, kind);
    }
    if (isFile || line === null || line === undefined) {
        fileKeys.set(`${det}::${normFile}`, kind);
    }
}

function lookupLineSuppression(lineKeys, detectors, file, line) {
    if (!file || line === null || line === undefined) return null;
    for (const d of detectors) {
        if (!d) continue;
        for (const ln of [line, line - 1, line + 1]) {
            const hit = lineKeys.get(`${d}::${file}::${ln}`);
            if (hit) return hit;
        }
    }
    return null;
}

function matchLedgerIssue(lineKeys, fileKeys, issue) {
    if (!issue) return null;
    const det = String(issue.detector || "").toLowerCase();
    const cat = String(issue.category || "").toLowerCase();
    const file = normalizeLedgerFile(issue.file);
    const detectors = [det, cat, "all", "*"];
    const lineHit = lookupLineSuppression(lineKeys, detectors, file, issue.line);
    if (lineHit) return lineHit;
    if (!file) return null;
    for (const d of detectors) {
        if (!d) continue;
        const hit = fileKeys.get(`${d}::${file}`);
        if (hit) return hit;
    }
    return null;
}

function summarizeSuppressionLedger(entries, totalDetectedCount) {
    const ignoredByDetector = {};
    for (const e of entries.values()) {
        ignoredByDetector[e.detector] = (ignoredByDetector[e.detector] || 0) + 1;
    }
    const ignoredCount = entries.size;
    const denom = ignoredCount + Math.max(0, Number(totalDetectedCount) || 0);
    const suppressedPct = denom > 0 ? Math.round((ignoredCount / denom) * 1000) / 10 : 0;
    return {
        ignored_count: ignoredCount,
        suppressed_pct: suppressedPct,
        ignored_by_detector: ignoredByDetector,
    };
}

export function createSuppressionLedger() {
    const entries = new Map();
    const lineKeys = new Map();
    const fileKeys = new Map();

    return {
        record(detector, file = null, line = null, kind = "inline", isFile = false) {
            recordSuppressionLedgerEntry(entries, lineKeys, fileKeys, detector, file, line, kind, isFile);
        },
        matchIssue(issue) {
            return matchLedgerIssue(lineKeys, fileKeys, issue);
        },
        summary(totalDetectedCount = 0) {
            return summarizeSuppressionLedger(entries, totalDetectedCount);
        },
    };
}

/**
 * Load ignore rules from `.plexerignore`, `.reviewignore`, and `config.excludes`.
 * Supports `<glob>` or `<category>:<glob>`.
 */
export function loadIgnoreRules(rootDir, configExcludes = [], ledger = null) {
    const rules = [];
    const addRawLine = (raw, fromConfigExclude = false) => {
        const line = raw.trim();
        if (!line || line.startsWith("#")) return;
        let category = null;
        let pattern = line;
        const colonIdx = line.indexOf(":");
        if (colonIdx > 0 && !line.slice(0, colonIdx).includes("/")) {
            category = line.slice(0, colonIdx).trim().toLowerCase();
            pattern = line.slice(colonIdx + 1).trim();
        }
        const normPat = pattern.replace(/\\/g, "/").replace(/^\.\//, "").replace(/\/+$/, "");
        if (!normPat) return;
        const regex = normPat.includes("*") || normPat.includes("?") ? globToRegExp(normPat) : null;
        rules.push({ category, pattern: normPat, regex, fromConfigExclude });
    };

    for (const fname of [".plexerignore", ".reviewignore"]) {
        const p = join(rootDir, fname);
        if (existsSync(p)) {
            try {
                const content = readFileSync(p, "utf8");
                for (const line of content.split(/\r?\n/)) addRawLine(line, false);
            } catch {
                // Ignore unreadable files
            }
        }
    }

    for (const ex of configExcludes || []) {
        if (typeof ex === "string") addRawLine(ex, true);
    }

    return {
        rules,
        ledger,
        isIgnored: (relPath, detectorOrCategory = null) =>
            isPathIgnoredByRules(rules, relPath, detectorOrCategory, ledger),
    };
}

const INLINE_SUPPRESS_RE = /(?:\/\/|--|#|\/\*)\s*(?:plexer-ignore|plexer:\s*ignore|review:\s*ignore|selene:\s*allow)/i;

function buildSuppressionCandidates(lines, lineNum) {
    const candidates = [
        { line: lines[lineNum - 1], lineNo: lineNum, isPreceding: false },
        lineNum >= 2 ? { line: lines[lineNum - 2], lineNo: lineNum - 1, isPreceding: true } : null,
    ];
    const headerLimit = Math.min(5, lines.length);
    for (let k = 0; k < headerLimit; k++) {
        if (k !== lineNum - 1 && k !== lineNum - 2 && typeof lines[k] === "string" && /plexer-ignore-file/i.test(lines[k])) {
            candidates.push({ line: lines[k], lineNo: k + 1, isPreceding: false });
        }
    }
    return candidates;
}

function lineMatchesInlineSuppression(line, isPreceding, detNorm, detLower, detCat) {
    if (isPreceding && !/^\s*(?:\/\/|--|#|\/\*)/.test(line)) return false;
    if (!INLINE_SUPPRESS_RE.test(line)) return false;
    const isSeleneOnly = /--\s*selene:\s*allow/i.test(line) && !/(?:plexer-ignore|plexer:\s*ignore|review:\s*ignore)/i.test(line);
    if (isSeleneOnly && detNorm && detNorm !== "luau_quality" && detNorm !== "language_traps") return false;
    const bracketMatch = /(?:plexer-ignore|plexer:\s*ignore|review:\s*ignore)(?:-file)?\s*\[([^\]]+)\]/i.exec(line);
    const colonMatch = !bracketMatch
        ? /(?:plexer-ignore|plexer:\s*ignore|review:\s*ignore)(?:-file)?\s*:\s*([A-Za-z0-9_,\s*-]+)/i.exec(line)
        : null;
    const rawSpec = bracketMatch ? bracketMatch[1] : colonMatch ? colonMatch[1] : null;
    if (rawSpec === null || !detNorm) return true;
    const tokens = rawSpec.replace(/(?:--|\/\/|#).*$/, "").trim().split(/[\s,]+/).map((s) => s.trim().toLowerCase().replace(/-/g, "_")).filter(Boolean);
    if (tokens.length === 0) return true;
    const detParts = detNorm.split("_");
    return tokens.some((t) => t === "all" || t === "*" || t === detNorm || t === detLower || (detCat && t === detCat) || detParts.includes(t));
}

/**
 * Check if `lineNum` (1-based), its preceding line, or a file-header `plexer-ignore-file` directive
 * in the first 5 lines has an inline suppression directive.
 */
export function hasInlineSuppression(lines, lineNum, detectorName = "", ledger = null, relPath = null) {
    if (!Array.isArray(lines) || lineNum < 1) return false;
    const detLower = String(detectorName || "").toLowerCase();
    const detNorm = detLower.replace(/-/g, "_");
    const detCat = DETECTOR_CATEGORY[detNorm] || DETECTOR_CATEGORY[detLower] || null;
    const activeLedger = ledger || lines._suppressionLedger || null;
    const activeFile = relPath || lines._relPath || null;
    for (const cand of buildSuppressionCandidates(lines, lineNum)) {
        if (!cand || typeof cand.line !== "string") continue;
        if (!lineMatchesInlineSuppression(cand.line, cand.isPreceding, detNorm, detLower, detCat)) continue;
        if (activeLedger) {
            const isFileDirective = /plexer-ignore-file/i.test(cand.line);
            activeLedger.record(detNorm || "all", activeFile, isFileDirective ? cand.lineNo : lineNum, "inline", isFileDirective);
        }
        return true;
    }
    return false;
}

function readLongBracketPrefix(s, start) {
    if (s[start] !== "[") return null;
    let j = start + 1;
    while (s[j] === "=") j += 1;
    if (s[j] !== "[") return null;
    const eqCount = j - start - 1;
    return { openLen: j - start + 1, close: `]${"=".repeat(eqCount)}]` };
}

function stepLuauBacktickBody(rawLine, st) {
    const ch = rawLine[st.i];
    if (ch === "\\") { st.i += 2; return; }
    if (ch === "`") { st.inBacktick = false; st.out += '"'; st.i += 1; return; }
    if (ch === "{") { st.interpStack.push(0); st.out += " "; st.i += 1; return; }
    st.i += 1;
}

function stepLuauBacktickInterp(ch, st) {
    const topIdx = st.interpStack.length - 1;
    if (ch === "{") {
        st.interpStack[topIdx] += 1;
        st.out += "{";
    } else if (st.interpStack[topIdx] === 0) {
        st.interpStack.pop();
        st.inBacktick = true;
        st.out += " ";
    } else {
        st.interpStack[topIdx] -= 1;
        st.out += "}";
    }
    st.i += 1;
}

function advanceLuauQuotedLiteral(rawLine, i, len, q) {
    let idx = i + 1;
    while (idx < len) {
        if (rawLine[idx] === "\\") { idx += 2; continue; }
        if (rawLine[idx] === q) return idx + 1;
        idx += 1;
    }
    return idx;
}

function stripLuauLine(rawLine) {
    const len = rawLine.length;
    const st = { out: "", interpStack: [], inBacktick: false, i: 0 };
    while (st.i < len) {
        if (st.inBacktick) { stepLuauBacktickBody(rawLine, st); continue; }
        const ch = rawLine[st.i];
        if (st.interpStack.length > 0 && (ch === "{" || ch === "}")) { stepLuauBacktickInterp(ch, st); continue; }
        if (ch === "-" && rawLine[st.i + 1] === "-") {
            const lb = readLongBracketPrefix(rawLine, st.i + 2);
            const closeIdx = lb ? rawLine.indexOf(lb.close, st.i + 2 + lb.openLen) : -1;
            st.out += " ";
            if (closeIdx >= 0) { st.i = closeIdx + lb.close.length; continue; }
            break;
        }
        if (ch === "[") {
            const lb = readLongBracketPrefix(rawLine, st.i);
            if (lb) {
                const closeIdx = rawLine.indexOf(lb.close, st.i + lb.openLen);
                st.out += '""';
                if (closeIdx < 0) break;
                st.i = closeIdx + lb.close.length;
                continue;
            }
        }
        if (ch === '"' || ch === "'") { st.i = advanceLuauQuotedLiteral(rawLine, st.i, len, ch); st.out += '""'; continue; }
        if (ch === "`") { st.inBacktick = true; st.out += '"'; st.i += 1; continue; }
        st.out += ch;
        st.i += 1;
    }
    return st.out;
}

function matchPythonStringPrefix(rawLine, idx) {
    if (idx > 0 && /[A-Za-z0-9_]/.test(rawLine[idx - 1])) return null;
    for (const pLen of [2, 1, 0]) {
        const pref = rawLine.slice(idx, idx + pLen);
        if (pLen > 0 && !/^[fFrRbBuU]{1,2}$/.test(pref)) continue;
        const qPos = idx + pLen;
        const qChar = rawLine[qPos];
        if (qChar !== '"' && qChar !== "'") continue;
        const triple = rawLine.slice(qPos, qPos + 3) === qChar.repeat(3) ? qChar.repeat(3) : qChar;
        return { prefixLen: pLen, quote: triple, isFString: /[fF]/.test(pref) };
    }
    return null;
}

function consumePythonQuotedLiteral(rawLine, startIdx, len, quote) {
    let i = startIdx;
    while (i < len) {
        if (rawLine.startsWith(quote, i)) return i + quote.length;
        if (rawLine[i] === "\\") {
            i += 2;
            continue;
        }
        i += 1;
    }
    return i;
}

function consumePythonFStringLiteral(rawLine, st, quote) {
    st.out += " ";
    while (st.i < st.len) {
        if (rawLine.startsWith(quote, st.i)) {
            st.i += quote.length;
            st.out += '"';
            return null;
        }
        if (rawLine[st.i] === "\\") {
            st.i += 2;
            continue;
        }
        if (rawLine[st.i] === "{") {
            if (rawLine[st.i + 1] === "{") {
                st.i += 2;
                continue;
            }
            st.fStringStack.push({ braceDepth: 0, quote });
            st.i += 1;
            return quote;
        }
        st.i += 1;
    }
    return null;
}

function stepPythonFStringBrace(ch, st) {
    const top = st.fStringStack[st.fStringStack.length - 1];
    if (ch === "{") {
        top.braceDepth += 1;
        st.out += "{";
        st.i += 1;
        return true;
    }
    if (ch === "}") {
        if (top.braceDepth === 0) {
            st.fStringStack.pop();
            st.activeFQuote = top.quote;
            st.i += 1;
            return true;
        }
        top.braceDepth -= 1;
        st.out += "}";
        st.i += 1;
        return true;
    }
    return false;
}

function stripPythonLine(rawLine) {
    const st = { out: "", len: rawLine.length, fStringStack: [], activeFQuote: null, i: 0 };
    while (st.i < st.len) {
        if (st.activeFQuote) {
            st.activeFQuote = consumePythonFStringLiteral(rawLine, st, st.activeFQuote);
            continue;
        }
        const ch = rawLine[st.i];
        if (st.fStringStack.length > 0 && stepPythonFStringBrace(ch, st)) continue;
        if (ch === "#") break;
        const spec = matchPythonStringPrefix(rawLine, st.i);
        if (spec) {
            st.i += spec.prefixLen + spec.quote.length;
            if (spec.isFString) {
                st.out += '"';
                st.activeFQuote = consumePythonFStringLiteral(rawLine, st, spec.quote);
                continue;
            }
            st.i = consumePythonQuotedLiteral(rawLine, st.i, st.len, spec.quote);
            st.out += '""';
            continue;
        }
        st.out += ch;
        st.i += 1;
    }
    return st.out;
}

export function stripCodeStringsAndComments(rawLine, isLuauOrLua = false, isPython = false) {
    if (typeof rawLine !== "string" || !rawLine) return "";
    if (isLuauOrLua) return stripLuauLine(rawLine);
    if (isPython) return stripPythonLine(rawLine);
    let s = rawLine;
    if (s.includes("`")) {
        // Strip non-interpolated template text segments first while keeping ${...} expressions intact
        s = s
            .replace(/`(?:\\.|[^`$\\]|\$(?!\{))*`/g, "``")
            .replace(/`(?:\\.|[^`$\\]|\$(?!\{))*\$\{/g, "${")
            .replace(/\}(?:\\.|[^`$\\]|\$(?!\{))*\$\{/g, "} ${")
            .replace(/\}(?:\\.|[^`$\\]|\$(?!\{))*`/g, "}");
    }
    return s
        .replace(/\/\*[\s\S]*?\*\//g, " ")
        .replace(/"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'/g, '""')
        .replace(/\/\/.*$/, "")
        .replace(/(?<=[=(,:!&|?[{;]\s*|^)\/(?:\\.|\[(?:\\.|[^\]\\])*\]|[^/\\\r\n*])(?:\\.|\[(?:\\.|[^\]\\])*\]|[^/\\\r\n])*\/[dgimsuvy]*/g, '""');
}

const WORD_TOKEN_RE_CACHE = new Map();
const MAX_WORD_TOKEN_CACHE = 8192;

export function hasWordToken(line, token) {
    if (!line || !token) return false;
    const str = typeof line === "string" ? line : String(line);
    const tok = typeof token === "string" ? token : String(token);
    if (!str.includes(tok)) return false;
    let re = WORD_TOKEN_RE_CACHE.get(tok);
    if (!re) {
        if (WORD_TOKEN_RE_CACHE.size >= MAX_WORD_TOKEN_CACHE) {
            WORD_TOKEN_RE_CACHE.clear();
        }
        const escaped = tok.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
        re = new RegExp(`(?<![A-Za-z0-9_$])${escaped}(?![A-Za-z0-9_$])`);
        WORD_TOKEN_RE_CACHE.set(tok, re);
    }
    return re.test(str);
}

/**
 * Compute updated Luau block nesting depth for `rawLine`, ignoring strings, comments,
 * and inline `if <cond> then <a> else <b>` conditional expressions (which have no `end`).
 */
export function stepLuauBlockDepth(depthOrLine, lineOrDepth = 0) {
    const depth = typeof depthOrLine === "number" ? depthOrLine : Number(lineOrDepth) || 0;
    const rawLine = typeof depthOrLine === "string" ? depthOrLine : String(lineOrDepth || "");
    const cleaned = stripCodeStringsAndComments(rawLine, true, false).trim();
    if (!cleaned) return depth;
    const withoutInlineIf = cleaned.replace(
        /([=(,{[\-+*/%^<>~]|==|~=|<=|>=|\.\.|\b(?:return|and|or|not)\b)\s*if\b(?:(?!\b(?:end|return|local)\b).)*?\bthen\b(?:(?!\b(?:end|return|local)\b).)*?\belse\b/g,
        "$1 ",
    );
    const opens = (withoutInlineIf.match(/\b(?:function|then|do|repeat)\b/g) || []).length;
    const elseifs = (withoutInlineIf.match(/\belseif\b/g) || []).length;
    const closes = (withoutInlineIf.match(/\b(?:end|until)\b/g) || []).length;
    return Math.max(0, depth + Math.max(0, opens - elseifs) - closes);
}

export class UnionFind {
    constructor(size = 0) {
        this.parent = new Map();
        this.rank = new Map();
        for (let i = 0; i < size; i++) {
            this.parent.set(i, i);
            this.rank.set(i, 0);
        }
    }
    makeSet(x) {
        if (!this.parent.has(x)) {
            this.parent.set(x, x);
            this.rank.set(x, 0);
        }
    }
    find(x) {
        if (!this.parent.has(x)) {
            this.makeSet(x);
            return x;
        }
        let cur = x;
        while (this.parent.get(cur) !== cur) {
            const p = this.parent.get(cur);
            const gp = this.parent.get(p);
            this.parent.set(cur, gp);
            cur = gp;
        }
        return cur;
    }
    union(a, b) {
        let ra = this.find(a);
        let rb = this.find(b);
        if (ra === rb) return false;
        const rankA = this.rank.get(ra) || 0;
        const rankB = this.rank.get(rb) || 0;
        if (rankA < rankB) {
            const tmp = ra;
            ra = rb;
            rb = tmp;
        }
        this.parent.set(rb, ra);
        if (rankA === rankB) this.rank.set(ra, rankA + 1);
        return true;
    }
    components() {
        const byRoot = new Map();
        for (const x of this.parent.keys()) {
            const r = this.find(x);
            let list = byRoot.get(r);
            if (!list) {
                list = [];
                byRoot.set(r, list);
            }
            list.push(x);
        }
        return [...byRoot.values()];
    }
    groups() {
        return this.components();
    }
}
